package de.oszimt.starsim2099.Oberklasse;

public abstract class Position {

	private double posX;
	private double posY;
	
	

	public double getPosX() {
		return posX;
	}

	public void setPosX(double pX) {
		this.posX = pX;
	}

	public double getPosY() {
		return posY;
	}

	public void setPosY(double pY) {
		this.posY = pY;
	}

}
