package de.oszimt.starsim2099;

public class Himmelskoerper {

	private String name;
	private double posX;
	private double posY;

	public Himmelskoerper() {

	}

	public String getName() {
		return this.name;
	}

	public void setName(String n) {
		this.name = n;
	}

	public double getPosX() {
		return this.posX;
	}

	public void setPosX(double pX) {
		this.posX = pX;
	}

	public double getPosY() {
		return this.posY;
	}

	public void setPosY(double pY) {
		this.posY = pY;
	}
}
